static uint8_t  luna_frame = 0;
static uint8_t  luna_x     = 0;   // 文字単位（1 文字 = 6 ドット）
static uint16_t luna_timer = 0;

void oledkit_render_logo_user(void)
{
  // USB 側の画面が消えているあいだは描かない（描くと画面が点いてしまう）
  if (!is_oled_on()) return;
  if (timer_elapsed(luna_timer) < LUNA_FRAME_MS) return;
  luna_timer = timer_read();
  luna_frame ^= 1;

  uint8_t wpm  = get_current_wpm();
  uint8_t mods = get_mods();
  uint8_t pose;
  if (mods & MOD_MASK_CTRL)                               pose = LUNA_SNEAK;
  else if (mods & MOD_MASK_SHIFT)                         pose = LUNA_BARK;
  else if (wpm <= LUNA_MIN_WALK_SPEED)                    pose = LUNA_SIT;
  else if (wpm <= LUNA_MIN_RUN_SPEED)                     pose = LUNA_WALK;
  else                                                    pose = LUNA_RUN;

  if (pose == LUNA_WALK || pose == LUNA_RUN) {
    luna_x += (pose == LUNA_RUN) ? 2 : 1;
    if (luna_x > 16) luna_x = 0;   // 右端まで行ったら左から出てくる
    oled_clear();
  }

  const char *p = luna_frames[pose][luna_frame];
  for (uint8_t page = 0; page < 3; page++) {
    oled_set_cursor(luna_x, page + 1);
    oled_write_raw_P(p + page * 32, 32);
  }
}
